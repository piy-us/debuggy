def add_nums(a, b, c=0):
    """
    Return the sum of two or three numbers.
    
    Parameters:
    a (int|float): First number.
    b (int|float): Second number.
    c (int|float, optional): Third number, defaults to 0.
    
    Returns:
    int|float: The sum of the provided numbers.
    """
    return a + b + c